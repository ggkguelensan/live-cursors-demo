import { mkdir, writeFile } from 'node:fs/promises';
const revision = '6233e3933e2f9685ff0c043765d83e01a2013eb6';
const files = {
  'src/imperative.ts': 'src/vendor/reflect/imperative.ts',
  'src/imperative/view-events.ts': 'src/vendor/reflect/imperative/view-events.ts',
  'public-types/imperative.d.ts': 'src/vendor/reflect/imperative.d.ts',
};
for (const [source, target] of Object.entries(files)) {
  const url = `https://raw.githubusercontent.com/ggkguelensan/reflect/${revision}/${source}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  await mkdir(target.slice(0, target.lastIndexOf('/')), { recursive: true });
  await writeFile(
    target,
    `// GENERATED by pnpm vendor:reflect. Do not edit independently.\n// Source (MIT): ${url}\n${await response.text()}`,
  );
}
console.log(`Vendored optional Reflect operator from ${revision}.`);
